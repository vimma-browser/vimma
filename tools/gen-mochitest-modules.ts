// Regenerates types/mochitest/modules.d.ts: each module Vimma ships under
// chrome://browser/content/vimma/, by URL, typed as its source module. The browser tests import
// Vimma's modules by that URL with ChromeUtils.importESModule, which types/firefox.d.ts types
// through this map (VimmaModules), so a test is checked against the product's own JSDoc; any other
// URL (Firefox's own modules, a URL held in a variable) keeps returning `any`. The map follows
// src/browser/base/content/vimma/jar.mn, and core/ (one jar.mn line for the whole package) follows
// the flat copy tools/sync-core.mjs makes of packages/vimma-core/src, which is what the URL serves
// and what the product's own `../core/` imports resolve to. tools/test/mochitest-modules.test.ts
// fails when this file drifts from jar.mn or the package.
//
//   npm run gen-mochitest-modules

import { readFileSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { flatCore } from "./sync-core.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = "types/mochitest/modules.d.ts";
const CHROME = "src/browser/base/content/vimma";
const PREFIX = "chrome://browser/content/vimma/";

/**
 * The ES modules a jar.mn ships under content/browser/vimma/: URL path -> source path relative to
 * the repository. A source in parentheses is relative to the jar.mn's folder, or to src/ when it
 * starts with `/`. The core/ line (a folder, not a file) is left to coreModules.
 */
export function jarModules(jar: string, dir: string = CHROME): Map<string, string> {
  const modules = new Map<string, string>();
  for (const line of jar.split("\n")) {
    const m = /^\s+content\/browser\/vimma\/(\S+)\s+\(([^)]+)\)\s*$/.exec(line);
    if (!m) continue;
    const [, url = "", source = ""] = m;
    if (!url.endsWith(".mjs")) continue;
    modules.set(url, source.startsWith("/") ? `src${source}` : posix.join(dir, source));
  }
  return modules;
}

/** core/'s modules: URL path -> the synced copy under src/, from the package's flat layout. */
export function coreModules(): Map<string, string> {
  const modules = new Map<string, string>();
  for (const dest of flatCore(join(ROOT, "packages/vimma-core/src")).keys()) {
    if (dest.endsWith(".mjs")) modules.set(`core/${dest}`, `${CHROME}/core/${dest}`);
  }
  return modules;
}

/** The text of types/mochitest/modules.d.ts, as jar.mn and the package lay the modules out now. */
export async function moduleTypes(): Promise<string> {
  const jar = readFileSync(join(ROOT, CHROME, "jar.mn"), "utf8");
  const all = new Map([...jarModules(jar), ...coreModules()]);
  const rows = [...all]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([url, source]) => `  "${PREFIX}${url}": typeof import("../../${source}");`);
  const text =
    "// Generated by tools/gen-mochitest-modules.ts from src/browser/base/content/vimma/jar.mn\n" +
    "// and packages/vimma-core/src: do not edit. Run `npm run gen-mochitest-modules` after adding,\n" +
    "// moving or removing a module.\n\n" +
    "/** Vimma's modules by chrome:// URL, for ChromeUtils.importESModule (types/firefox.d.ts). */\n" +
    `interface VimmaModules {\n${rows.join("\n")}\n}\n`;
  const config = (await resolveConfig(join(ROOT, OUT))) ?? {};
  return format(text, { ...config, parser: "typescript" });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, OUT), await moduleTypes());
}
