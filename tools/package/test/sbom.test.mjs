/**
 * An engine tree with Cargo.lock, vendored crates and moz.yaml files, in a temp dir the caller
 * removes.
 * @returns {string}
 */
function fakeEngine() {
  const root = mkdtempSync(join(tmpdir(), "vimma-engine-"));
  /** @type {Record<string, string>} */
  const files = {
    "Cargo.lock": CARGO_LOCK,
    // two versions of a crate in the lock: cargo vendor suffixes the directory with the version
    "third_party/rust/base64/Cargo.toml":
      '[package]\nname = "base64"\nversion = "0.22.1"\nlicense = "MIT OR Apache-2.0"\n',
    "third_party/rust/euclid/Cargo.toml":
      '[package]\nname = "euclid"\nlicense = "MIT/Apache-2.0"\n',
    "third_party/pd/moz.yaml": "origin:\n  name: pd\n  release: 1\n  license: Public Domain\n",
    "media/libpng/moz.yaml":
      "origin:\n  name: libpng\n  release: 1.6.43 (2024-02-23).\n  license: libpng\n",
    "media/libvpx/moz.yaml": LIBVPX,
    "third_party/dav1d/moz.yaml": LISTED,
    "obj-x86_64-pc-linux-gnu/ignored/moz.yaml": LISTED.replace("dav1d", "ignored"),
  };
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  return root;
}

describe("parseCargoLock", () => {
  it("returns every package with its source and checksum", () => {
    const packages = parseCargoLock(CARGO_LOCK);
    expect(packages).toHaveLength(4);
    expect(packages[2]).toEqual({
      name: "base64",
      version: "0.22.1",
      source: "registry+https://github.com/rust-lang/crates.io-index",
      checksum: "72b3254f16251a8381aa12e40e3c4d2f0199f8c6508fbecb9d91f575e0fbb8c6",
    });
    expect(packages[1]?.source).toBeUndefined();
  });
});

describe("parseMozYaml", () => {
  it("reads origin's name, release, revision, licence and URL, not other sections'", () => {
    expect(parseMozYaml(LIBVPX)).toEqual({
      name: "libvpx",
      url: "https://chromium.googlesource.com/webm/libvpx",
      release: "5c880e08d21386049adec8e5537c4e726458b563 (Thu Aug 27 16:55:36 2026).",
      revision: "5c880e08d21386049adec8e5537c4e726458b563",
      licenses: ["BSD-3-Clause"],
    });
  });

  it("reads a licence list and strips quotes", () => {
    expect(parseMozYaml(LISTED)).toMatchObject({
      name: "dav1d",
      licenses: ["BSD-2-Clause", "ISC"],
    });
  });

  it("reads a flow-style licence list and keeps a licence name that is not an SPDX id", () => {
    const text =
      "origin:\n  name: libjpeg\n  release: '3.0'\n  license: ['IJG', \"BSD-3-Clause\"]\n";
    expect(parseMozYaml(text)).toMatchObject({ release: "3.0", licenses: ["IJG", "BSD-3-Clause"] });
    expect(parseMozYaml("origin:\n  name: x\n  license: Public Domain\n")?.licenses).toEqual([
      "Public Domain",
    ]);
  });

  it("returns null without an origin name", () => {
    expect(parseMozYaml("schema: 1\nbugzilla:\n  product: Core\n")).toBeNull();
  });
});

describe("buildSbom", () => {
  // Built once while the describe is collected, outside any test: the engine goes right after.
  const engine = fakeEngine();
  /** @type {ReturnType<typeof buildSbom>} */
  let bom;
  try {
    bom = buildSbom({
      engineDir: engine,
      config: {
        version: { product: "firefox", version: "157.0.1" },
        brands: { vimma: { release: { displayVersion: "0.1.0" } } },
      },
      repo: "vimma-browser/vimma",
      vimmaRoot: ROOT,
      serialNumber: "urn:uuid:00000000-0000-4000-8000-000000000000",
      timestamp: "2026-10-09T00:00:00Z",
    });
  } finally {
    rmSync(engine, { recursive: true, force: true });
  }
  /** @param {string} name */
  const component = (name) => bom.components.find((c) => c.name === name);

  it("is a CycloneDX 1.6 document about Vimma", () => {
    expect(bom.bomFormat).toBe("CycloneDX");
    expect(bom.specVersion).toBe("1.6");
    expect(bom.serialNumber).toMatch(/^urn:uuid:[0-9a-f-]{36}$/);
    expect(bom.version).toBe(1);
    expect(bom.metadata.timestamp).toBe("2026-10-09T00:00:00Z");
    expect(bom.metadata.component).toMatchObject({
      type: "application",
      name: "vimma",
      version: "0.1.0",
      purl: "pkg:github/vimma-browser/vimma@v0.1.0",
      licenses: [{ license: { id: "MPL-2.0" } }],
    });
  });

  it("says it lists what the source tree vendors", () => {
    const scope = bom.metadata.properties.find((p) => p.name === "vimma:sbom:scope");
    expect(scope?.value).toMatch(/superset/);
  });

  it("lists Firefox", () => {
    expect(component("firefox")).toMatchObject({
      version: "157.0.1",
      purl: "pkg:generic/mozilla/firefox@157.0.1",
      licenses: [{ license: { id: "MPL-2.0" } }],
    });
  });

  it("lists registry crates with purl, hash and licence from the vendored Cargo.toml", () => {
    // the old "MIT/Apache-2.0" form is not an SPDX expression; it is written as one
    expect(component("base64")?.licenses).toEqual([{ expression: "MIT OR Apache-2.0" }]);
    expect(component("euclid")).toMatchObject({
      type: "library",
      version: "0.22.11",
      purl: "pkg:cargo/euclid@0.22.11",
      hashes: [
        {
          alg: "SHA-256",
          content: "ad9cdb4b747e485a12abb0e6566612956c7a1bafa3bdb8d682c5b6d403589e48",
        },
      ],
      licenses: [{ expression: "MIT OR Apache-2.0" }],
    });
  });

  it("leaves out in-tree crates and gives git crates their repository", () => {
    expect(bom.components.filter((c) => c.name === "base64").map((c) => c.version)).toEqual([
      "0.22.1",
    ]);
    expect(component("aa-stroke")?.externalReferences).toEqual([
      {
        type: "vcs",
        url: "https://github.com/FirefoxGraphics/aa-stroke?rev=5776bdf#5776bdfc8ad664a1503db668fab397d818a5f98a",
      },
    ]);
    expect(component("aa-stroke")?.licenses).toBeUndefined();
  });

  it("lists moz.yaml libraries outside the objdir", () => {
    expect(component("libvpx")).toMatchObject({
      version: "5c880e08d21386049adec8e5537c4e726458b563",
      purl: "pkg:generic/libvpx@5c880e08d21386049adec8e5537c4e726458b563",
      licenses: [{ license: { id: "BSD-3-Clause" } }],
      externalReferences: [
        { type: "website", url: "https://chromium.googlesource.com/webm/libvpx" },
      ],
    });
    expect(component("dav1d")?.licenses).toEqual([
      { license: { id: "BSD-2-Clause" } },
      { license: { id: "ISC" } },
    ]);
    expect(component("ignored")).toBeUndefined();
    expect(component("pd")?.licenses).toEqual([{ license: { name: "Public Domain" } }]);
  });

  it("strips the date from a release without a revision", () => {
    expect(component("libpng")).toMatchObject({
      version: "1.6.43",
      purl: "pkg:generic/libpng@1.6.43",
      licenses: [{ license: { id: "Libpng" } }],
    });
  });

  it("lists the smol-toml we vendor into vimma-core", () => {
    expect(component("smol-toml")).toMatchObject({
      type: "library",
      version: "1.9.0",
      purl: "pkg:npm/smol-toml@1.9.0",
      licenses: [{ license: { id: "BSD-3-Clause" } }],
    });
  });

  it("validates against the official CycloneDX 1.6 schema", () => {
    const validate = validator();
    const ok = validate(bom);
    expect(validate.errors ?? []).toEqual([]);
    expect(ok).toBe(true);
  });

  it("the schema rejects a licence id that is not SPDX's spelling", () => {
    const validate = validator();
    const bad = structuredClone(bom);
    bad.components[0].licenses = [{ license: { id: "libpng" } }];
    expect(validate(bad)).toBe(false);
  });

  it("gives every component a unique bom-ref", () => {
    const refs = bom.components.map((c) => c["bom-ref"]);
    expect(new Set(refs).size).toBe(refs.length);
  });
});

// Issue #516: the release packages ship vimma-ctl, so the release SBOM lists it with the libraries
// its toolchain linked into it, as ctl-notices.mjs describes them in release.yml's ctl job.
describe("addCtlComponent", () => {
  const ctl = {
    type: "application",
    "bom-ref": "pkg:github/vimma-browser/vimma@v0.1.0#tools/vimma-ctl",
    name: "vimma-ctl",
    version: "0.1.0",
    purl: "pkg:github/vimma-browser/vimma@v0.1.0#tools/vimma-ctl",
    licenses: [{ license: { id: "MPL-2.0" } }],
    hashes: [{ alg: "SHA-256", content: "a".repeat(64) }],
    properties: [{ name: "vimma:rust-target", value: "x86_64-unknown-linux-musl" }],
    components: [
      {
        type: "library",
        "bom-ref": "pkg:generic/rust-lang/rust-std@1.99.1#vimma-ctl",
        group: "rust-lang",
        name: "rust-std",
        version: "1.99.1",
        purl: "pkg:generic/rust-lang/rust-std@1.99.1",
        licenses: [{ expression: "Apache-2.0 OR MIT" }],
      },
      {
        type: "library",
        "bom-ref": "pkg:generic/musl@1.2.5#vimma-ctl",
        name: "musl",
        version: "1.2.5",
        purl: "pkg:generic/musl@1.2.5",
        licenses: [{ license: { id: "MIT" } }],
      },
    ],
  };
  const base = () =>
    buildSbom({
      engineDir: tempDir("vimma-engine-"),
      config: {
        version: { product: "firefox", version: "157.0.1" },
        brands: { vimma: { release: { displayVersion: "0.1.0" } } },
      },
      repo: "vimma-browser/vimma",
      serialNumber: "urn:uuid:00000000-0000-4000-8000-000000000000",
      timestamp: "2026-10-09T00:00:00Z",
    });

  it("lists vimma-ctl with what it links, and says so in the scope", () => {
    const bom = addCtlComponent(base(), ctl);
    expect(bom.components.at(-1)).toEqual(ctl);
    const scope = bom.metadata.properties.find((p) => p.name === "vimma:sbom:scope");
    expect(scope?.value).toMatch(/superset/);
    expect(scope?.value).toMatch(/vimma-ctl/);
    const validate = validator();
    expect(validate(bom), JSON.stringify(validate.errors)).toBe(true);
  });

  it("refuses anything but vimma-ctl of the release's version", () => {
    expect(() => addCtlComponent(base(), { ...ctl, name: "other" })).toThrow(/vimma-ctl/);
    expect(() => addCtlComponent(base(), { ...ctl, version: "0.0.9" })).toThrow(/0\.0\.9.*0\.1\.0/);
  });

  it("refuses a second vimma-ctl", () => {
    expect(() => addCtlComponent(addCtlComponent(base(), ctl), ctl)).toThrow(/already/);
  });
});

describe("canonicalLicense", () => {
  it.each([
    ["libpng", { license: { id: "Libpng" } }],
    ["mit", { license: { id: "MIT" } }],
    ["LGPL-2.1", { license: { id: "LGPL-2.1" } }],
    ["mit or apache-2.0", { expression: "MIT OR Apache-2.0" }],
    ["MIT/Apache-2.0", { expression: "MIT OR Apache-2.0" }],
    [
      "(Apache-2.0 OR MIT) AND BSD-3-Clause",
      { expression: "(Apache-2.0 OR MIT) AND BSD-3-Clause" },
    ],
    [
      "Apache-2.0 WITH LLVM-exception OR MIT",
      { expression: "Apache-2.0 WITH LLVM-exception OR MIT" },
    ],
    ["MIT-like", { license: { name: "MIT-like" } }],
    ["Public Domain", { license: { name: "Public Domain" } }],
    ["MIT OR Nonsense-1.0", { license: { name: "MIT OR Nonsense-1.0" } }],
  ])("%s", (input, expected) => {
    expect(canonicalLicense(input)).toEqual(expected);
  });
});
