// Regenerates types/mochitest/head.d.ts: the global declarations of tests/browser's shared
// helpers, emitted by tsc from their JSDoc. The harness loads head.js into every test's scope,
// and a test loads a head_*.js file into its own with Services.scriptloader.loadSubScript, so a
// test file uses their names without importing them; the type check of tests/ (tests/tsconfig.json)
// sees them through this file. Every head file is declared to every test, which is wider than a
// test that loads none of a head_*.js file sees at run time: such a test fails on the missing
// name the first time it runs. tools/test/mochitest-head-types.test.ts fails when this file
// drifts from the head files.
//
//   npm run gen-mochitest-head

import { spawnSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = "types/mochitest/head.d.ts";
const TSC = fileURLToPath(new URL("../node_modules/typescript/bin/tsc", import.meta.url));

/** The shared helper files of tests/browser, sorted. */
export function headFiles(): string[] {
  return readdirSync(join(ROOT, "tests/browser"))
    .filter((name) => /^head(_[a-z_]+)?\.js$/.test(name))
    .sort()
    .map((name) => `tests/browser/${name}`);
}

/** The text of types/mochitest/head.d.ts, as the head files declare it now. */
export async function headTypes(): Promise<string> {
  const out = mkdtempSync(join(tmpdir(), "vimma-mochitest-head-"));
  try {
    // A script (not a module) declares its top-level names globally, which is how the harness
    // runs a head file. No --checkJs: the head files are checked with the tests, in
    // tests/tsconfig.json; this only emits.
    const tsc = spawnSync(
      process.execPath,
      [
        TSC,
        "--ignoreConfig",
        "--allowJs",
        "--declaration",
        "--emitDeclarationOnly",
        "--outDir",
        out,
        "--rootDir",
        ROOT,
        "--module",
        "preserve",
        "--moduleDetection",
        "legacy",
        "--target",
        "es2024",
        "--types",
        "",
        "--skipLibCheck",
        "--strict",
        ...headFiles(),
        "types/firefox.d.ts",
        "types/mochitest/harness.d.ts",
        "types/mochitest/firefox.d.ts",
      ],
      { cwd: ROOT, encoding: "utf8" },
    );
    if (tsc.status !== 0) throw new Error(`tsc failed:\n${tsc.stdout}${tsc.stderr}`);
    const parts = headFiles().map((file) => {
      const dts = readFileSync(join(out, file.replace(/\.js$/, ".d.ts")), "utf8");
      return `// ${file}\n\n${dts.trim()}\n`;
    });
    const text =
      "// Generated by tools/gen-mochitest-head.ts from tests/browser's head files: do not edit.\n" +
      "// Run `npm run gen-mochitest-head` after changing one.\n\n" +
      parts.join("\n");
    const config = (await resolveConfig(join(ROOT, OUT))) ?? {};
    return format(text, { ...config, parser: "typescript" });
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, OUT), await headTypes());
}
