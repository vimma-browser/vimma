"""Prints the East Asian Wide (W) and Fullwidth (F) code point ranges table for
packages/vimma-core/src/text/textwidth.mjs from Python's bundled Unicode Character Database
(`unicodedata`; its UCD version goes into the header). Paste the output over the table.

    python3 tools/unicode/gen_wide_ranges.py
"""
import sys
import unicodedata

ranges = []
for cp in range(sys.maxunicode + 1):
    if unicodedata.east_asian_width(chr(cp)) in ("W", "F"):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

print(f"// Generated by tools/unicode/gen_wide_ranges.py from UCD {unicodedata.unidata_version}")
print("// EastAsianWidth.txt, classes W and F, as [first, last] pairs. Do not edit by hand.")
print("// prettier-ignore")
print("const WIDE = [")
line = " "
for a, b in ranges:
    item = f" 0x{a:x}, 0x{b:x},"
    if len(line) + len(item) > 98:
        print(line)
        line = " "
    line += item
print(line)
print("];")
