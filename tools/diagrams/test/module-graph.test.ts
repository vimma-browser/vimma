import { describe, expect, test } from "vitest";
import type { Edge as FileEdge, Exception } from "../../layering/layering.ts";
import {
  type Edge,
  cycleGroups,
  folderEdges,
  inputErrors,
  lineDiff,
  toD2,
} from "../module-graph.ts";

const file = (from: string, to: string, kind: FileEdge["kind"] = "eager"): FileEdge => ({
  from,
  to,
  kind,
  line: 1,
});

describe("folderEdges", () => {
  test("one edge per pair of folders, eager when any import is, sorted, none to itself", () => {
    const edges = [
      file("ctl/VimmaControl.sys.mjs", "host/VimmaHost.sys.mjs"),
      file("ctl/VimmaControl.sys.mjs", "ctl/AgentGate.sys.mjs"),
      file("ctl/VimmaControl.sys.mjs", "ui/notice.mjs", "lazy"),
      file("ctl/VimmaControl.sys.mjs", "host/runners.mjs", "lazy"),
      file("host/VimmaHost.sys.mjs", "ctl/VimmaControl.sys.mjs", "lazy"),
      file("host/VimmaHost.sys.mjs", "ui/notice.mjs"),
      file("ui/notice.mjs", "core/keys.mjs"),
      // A URL prefix names a folder; vimma.js is the root.
      file("vimma.js", "host/"),
      file("start/start.html", "start/start.mjs"),
    ];
    expect(folderEdges(edges)).toEqual([
      { from: "(root)", to: "host", kind: "eager" },
      { from: "ctl", to: "host", kind: "eager" },
      { from: "ctl", to: "ui", kind: "lazy" },
      { from: "host", to: "ctl", kind: "lazy" },
      { from: "host", to: "ui", kind: "eager" },
      { from: "ui", to: "core", kind: "eager" },
    ]);
  });
});

describe("cycleGroups", () => {
  const e = (from: string, to: string, kind: Edge["kind"] = "eager"): Edge => ({ from, to, kind });

  test("the folders that reach each other through eager imports, largest group first", () => {
    const edges = [
      e("a", "b"),
      e("b", "a"),
      e("host", "ui"),
      e("ui", "agent"),
      e("agent", "host"),
      e("ui", "core"),
      e("x", "core"),
    ];
    expect(cycleGroups(edges)).toEqual([
      ["agent", "host", "ui"],
      ["a", "b"],
    ]);
  });

  test("a loop closed only by a lazy import is not an eager cycle", () => {
    expect(cycleGroups([e("host", "ctl"), e("ctl", "host", "lazy")])).toEqual([]);
    expect(cycleGroups([e("host", "ctl"), e("ctl", "host", "lazy")], "any")).toEqual([
      ["ctl", "host"],
    ]);
  });
});

describe("toD2", () => {
  const e = (from: string, to: string, kind: Edge["kind"] = "eager"): Edge => ({ from, to, kind });
  const layers = { core: 0, ui: 1, split: 1, actors: 2, host: 3, ctl: 4, start: 6, "(root)": 7 };
  const exceptions: Exception[] = [
    {
      from: "actors/P.sys.mjs",
      to: "host/H.sys.mjs",
      kind: "eager",
      reason: "r",
      fate: "goes",
      issue: 936,
    },
    {
      from: "host/H.sys.mjs",
      to: "ctl/G.sys.mjs",
      kind: "lazy",
      reason: "r",
      fate: "goes",
      issue: 936,
    },
  ];
  const edges: Edge[] = [
    e("host", "actors"),
    e("actors", "host"),
    e("ctl", "host"),
    e("host", "ctl", "lazy"),
    e("host", "split"),
    e("start", "ui"),
    e("(root)", "host"),
    e("(root)", "ctl"),
    e("(root)", "ui"),
    e("(root)", "split"),
    e("(root)", "start"),
    e("(root)", "actors"),
    e("host", "core"),
    e("ui", "core"),
    e("ctl", "core"),
    e("split", "core"),
    e("actors", "core"),
  ];
  const d2 = toD2(edges, layers, exceptions);

  test("says it is generated and how to regenerate it", () => {
    expect(d2.split("\n")[0]).toMatch(/^# Generated by npm run diagrams/);
  });

  test("labels each folder with its ADR-026 layer, top layer first", () => {
    expect(d2).toContain(`start: "start/ · 6" { class: folder }`);
    expect(d2).toContain(`ctl: "ctl/ · 4" { class: folder }`);
    expect(d2).toContain(`split: "split/ · 1" { class: folder }`);
    expect(d2.indexOf("start:")).toBeLessThan(d2.indexOf("ctl:"));
    expect(d2.indexOf("ctl:")).toBeLessThan(d2.indexOf("split:"));
    // No node for vimma.js or core/, and no band where no arrows merge.
    expect(d2).not.toMatch(/^(?:_root_|core):/m);
    expect(d2).not.toMatch(/layer\d: "/);
  });

  test("invisible links hold each folder above the next lower layer it does not import", () => {
    // start/ imports only ui/, two layers further down; ctl/ is the next layer below it.
    expect(d2).toContain("start -> ctl { class: order }");
    // actors/ imports nothing of layer 1 drawn here.
    expect(d2).toContain("actors -> split { class: order }");
    // ctl/ already imports host/, and host/ actors/.
    expect(d2).not.toMatch(/^ctl -> host \{ class: order/m);
    expect(d2).not.toMatch(/^host -> actors \{ class: order/m);
  });

  test("draws an import down the layers in the neutral style", () => {
    expect(d2).toContain("ctl -> host { class: down }");
    expect(d2).toContain("start -> ui { class: down }");
  });

  test("draws an upward import, one ADR-026 lists, in the warning style, target first", () => {
    expect(d2).toContain("host <- actors { class: up }");
    expect(d2).toContain("ctl <- host { class: up-lazy }");
    expect(d2).not.toMatch(/-> .*class: up/);
  });

  test("the legend counts the exceptions, names the cycle and says what vimma.js and core/ import", () => {
    expect(d2).toContain(
      "Orange: the 2 upward imports tools/layering/layers.ts lists, one arrow per pair of folders",
    );
    expect(d2).toContain("(#936 removes them)");
    expect(d2).toContain("Eager cycle, closed only by orange arrows: actors/, host/.");
    expect(d2).toContain("vimma.js imports every folder drawn here.");
    expect(d2).toContain("core/ is imported by every folder drawn here except start/.");
  });

  test("with no exception, the legend says nothing points up instead of counting none", () => {
    const down = [e("(root)", "host"), e("host", "ui"), e("ctl", "host"), e("ui", "core")];
    const out = toD2(down, layers, []);
    expect(out).toContain("No arrow points up: ADR-026 allows no upward import.");
    expect(out).not.toContain("Orange");
    expect(out).not.toContain("Eager cycle");
  });

  test("imports into several folders of a band of three or more are one arrow to the band", () => {
    const wide = { ...layers, search: 1, updates: 1 };
    const more = [
      ...edges,
      e("host", "search"),
      e("host", "updates", "lazy"),
      e("ctl", "split"),
      e("start", "search", "lazy"),
      e("start", "split", "lazy"),
    ];
    const out = toD2(more, wide, exceptions);
    // host/ reaches split/, search/ and updates/: one arrow, eager since one import is.
    expect(out).toContain(`layer1: "Layer 1" {`);
    expect(out).toContain(`  search: "search/ · 1" { class: folder }`);
    expect(out).toContain(`host -> layer1: "3" { class: down }`);
    expect(out).not.toMatch(/^host -> layer1\./m);
    // start/ reaches ui/ eagerly and two more lazily: eager.
    expect(out).toContain(`start -> layer1: "3" { class: down }`);
    // ctl/ reaches only split/ there: its own arrow.
    expect(out).toContain("ctl -> layer1.split { class: down }");
    // The band, not a folder in it, holds the folders above it in place.
    expect(out).toContain("actors -> layer1 { class: order }");
    expect(out).toContain("An arrow to a band: imports that many of its folders.");
    // In the two-folder band of the fixture, nothing is merged.
    expect(d2).not.toMatch(/-> layer\d: "/);
  });

  test("a folder that imports only core/ is drawn alone", () => {
    const alone = toD2(
      [...edges, e("services", "core"), e("(root)", "services")],
      { ...layers, services: 1 },
      exceptions,
    );
    expect(alone).toContain(`services: "services/ · 1" { class: folder }`);
    expect(alone).not.toMatch(/services ->/);
  });

  test("the same edges in any order give the same text", () => {
    expect(toD2([...edges].reverse(), layers, exceptions)).toBe(d2);
  });

  test("refuses an upward import that no exception lists, rather than colour it as listed", () => {
    expect(() => toD2([...edges, e("split", "host")], layers, exceptions)).toThrow(
      "split/ imports host/ upwards, and no exception in tools/layering/layers.ts lists it: npm run layering says more",
    );
  });
});

describe("inputErrors", () => {
  const layers = { core: 0, split: 1, host: 3 };
  const listed: Exception[] = [
    {
      from: "split/a.mjs",
      to: "host/H.sys.mjs",
      kind: "lazy",
      reason: "r",
      fate: "goes",
      issue: 1,
    },
  ];

  test("passes edges that follow the layers or are listed", () => {
    expect(
      inputErrors(
        [file("host/H.sys.mjs", "split/a.mjs"), file("split/a.mjs", "host/H.sys.mjs", "lazy")],
        [],
        layers,
        listed,
      ),
    ).toEqual([]);
  });

  test("reports what npm run layering would, so the picture is never drawn from a broken tree", () => {
    const errors = inputErrors(
      [file("split/a.mjs", "host/H.sys.mjs", "lazy"), file("split/b.mjs", "host/H.sys.mjs")],
      ["split/c.mjs:3: an import specifier is not a fixed string"],
      layers,
      listed,
    );
    expect(errors[0]).toBe("split/c.mjs:3: an import specifier is not a fixed string");
    expect(errors[1]).toMatch(/^split\/b\.mjs:1 imports host\/H\.sys\.mjs \(eager\)/);
    expect(errors).toHaveLength(2);
  });
});

describe("lineDiff", () => {
  test("names the lines only the committed file has, then those only the imports give", () => {
    expect(lineDiff("a\nb\nc\n", "a\nc\nd\n")).toEqual(["- b", "+ d"]);
    expect(lineDiff("a\n", "a\n")).toEqual([]);
  });
});
