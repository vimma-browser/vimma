const REV = "737ec77d798755890b062aab541a90d6c75afd19";
/** Firefox 159.0b1's source tarball (docs/specs/upstream-beta-canary.md, R3). */
const BETA_REV = "c0c03f3f899017ae4b7e56c0713f1ada51173c41";
const RELEASE = { tree: "releases/mozilla-release", revision: REV };
const BETA = { tree: "releases/mozilla-beta", revision: BETA_REV };

/** The shape of engine/mozconfig as `npm run import` writes it (configs/common + linux + Surfer). */
const GENERATED = [
  "ac_add_options --with-app-name=vimma",
  'export MOZ_USER_DIR="Vimma"',
  "export MOZ_APP_BASENAME=Vimma",
  "export MOZ_DISTRIBUTION_ID=dev.vimma.browser",
  "export MOZ_SOURCE_REPO=https://github.com/vimma-browser/vimma",
  "ac_add_options --enable-bootstrap",
  "ac_add_options --disable-crashreporter",
  "ac_add_options --with-version-file-path=browser/config/vimma",
  "ac_add_options --enable-application=browser",
  "ac_add_options --enable-hardening",
  "ac_add_options --enable-rust-simd",
  "ac_add_options --enable-release",
  "ac_add_options --enable-optimize",
  "ac_add_options --with-ccache=sccache",
  "ac_add_options --disable-debug",
  "ac_add_options --disable-updater",
  "ac_add_options --with-branding=browser/branding/vimma",
  "ac_add_options --enable-update-channel=vimma",
  "",
].join("\n");

/** @param {string} text */
const options = (text) =>
  text
    .split("\n")
    .filter((l) => /^\s*(ac|mk)_add_options\b/.test(l))
    .map((l) => l.trim());

describe("artifactMozconfig", () => {
  it("drops the options an artifact build rejects or cannot honour", () => {
    const out = options(artifactMozconfig(GENERATED));
    for (const dropped of [
      "--enable-optimize", // configure: not available in this configuration
      "--enable-hardening", // configure: not available in this configuration
      "--disable-crashreporter", // Mozilla's libxul then aborts on a missing CrashService.sys.mjs
      "--disable-updater", // Mozilla's libxul then aborts on a missing UpdateServiceStub.sys.mjs
      "--with-ccache=sccache", // nothing is compiled
    ]) {
      expect(out.some((l) => l.includes(dropped))).toBe(false);
    }
  });

  it("keeps our branding, app name, version files and release options", () => {
    const out = options(artifactMozconfig(GENERATED));
    for (const kept of [
      "ac_add_options --with-app-name=vimma",
      "ac_add_options --with-version-file-path=browser/config/vimma",
      "ac_add_options --with-branding=browser/branding/vimma",
      "ac_add_options --enable-release",
      "ac_add_options --enable-bootstrap",
      "ac_add_options --enable-update-channel=vimma",
    ]) {
      expect(out).toContain(kept);
    }
    for (const env of ['export MOZ_USER_DIR="Vimma"', "export MOZ_APP_BASENAME=Vimma"]) {
      expect(artifactMozconfig(GENERATED)).toContain(env);
    }
  });

  it("enables artifact builds in their own objdir", () => {
    const out = options(artifactMozconfig(GENERATED));
    expect(out).toContain("ac_add_options --enable-artifact-builds");
    expect(out).toContain(`mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/${ARTIFACT_OBJDIR}`);
    expect(ARTIFACT_OBJDIR).not.toBe("obj-x86_64-pc-linux-gnu");
  });

  it("says why each dropped line is gone, as a comment", () => {
    const text = artifactMozconfig(GENERATED);
    expect(text).toMatch(/^# artifact build drops: ac_add_options --enable-optimize/m);
    expect(text.split("\n")[0]).toMatch(/^# Generated by tools\/artifact-build/);
  });

  it("throws when the input already is an artifact mozconfig", () => {
    expect(() => artifactMozconfig(artifactMozconfig(GENERATED))).toThrow(/artifact/);
  });
});

describe("sourceStamp", () => {
  it("reads the tree from sourcestamp.txt", () => {
    const release = `20261005135250\nhttps://hg.mozilla.org/releases/mozilla-release/rev/${REV}\n`;
    expect(sourceStamp(release)).toEqual(RELEASE);
    const beta = `20261012000000\nhttps://hg.mozilla.org/releases/mozilla-beta/rev/${BETA_REV}\n`;
    expect(sourceStamp(beta)).toEqual(BETA);
  });

  it("refuses a tree other than mozilla-release or mozilla-beta", () => {
    for (const tree of [
      "mozilla-central",
      "releases/mozilla-esr140",
      "try",
      "releases/mozilla-beta/../x",
    ]) {
      const stamp = `20261005135250\nhttps://hg.mozilla.org/${tree}/rev/${REV}\n`;
      expect(() => sourceStamp(stamp), tree).toThrow(/mozilla-release or .*mozilla-beta/);
    }
  });

  it.each([
    ["an empty file", ""],
    ["no revision line", "20261005135250\n"],
    [
      "a short revision",
      "20261005135250\nhttps://hg.mozilla.org/releases/mozilla-release/rev/737ec77\n",
    ],
  ])("throws on %s", (_name, stamp) => {
    expect(() => sourceStamp(stamp)).toThrow(/sourcestamp/);
  });
});

describe("uaName", () => {
  it("reads MOZ_APP_UA_NAME from browser/moz.configure (src/browser/moz-configure.patch)", () => {
    const text =
      'imply_option("MOZ_APP_VENDOR", "Vimma")\nimply_option("MOZ_APP_UA_NAME", "Firefox")\n';
    expect(uaName(text)).toBe("Firefox");
  });

  it("is null when the flag is not implied (upstream's default)", () => {
    expect(uaName('imply_option("MOZ_APP_VENDOR", "Mozilla")\n')).toBeNull();
  });
});

describe("appIniForArtifact", () => {
  const INI = [
    "; This file is not used.",
    "[App]",
    "Vendor=Vimma",
    "Name=Vimma",
    "Version=157.0.1",
    "",
    "[Gecko]",
    "MinVersion=157.0.1",
    "",
  ].join("\n");

  it("adds UAName to [App], the runtime twin of the compiled-in MOZ_APP_UA_NAME", () => {
    const out = appIniForArtifact(INI, "Firefox");
    expect(out).toMatch(/^\[App\]\nUAName=Firefox\nVendor=Vimma$/m);
    expect(out.match(/UAName=/g)).toHaveLength(1);
  });

  it("replaces an existing UAName", () => {
    const out = appIniForArtifact(appIniForArtifact(INI, "Other"), "Firefox");
    expect(out.match(/UAName=/g)).toHaveLength(1);
    expect(out).toContain("UAName=Firefox");
  });

  it("leaves the file as is without a UA name", () => {
    expect(appIniForArtifact(INI, null)).toBe(INI);
  });

  it("throws without an [App] section", () => {
    expect(() => appIniForArtifact("[Gecko]\nMinVersion=1\n", "Firefox")).toThrow(/\[App\]/);
  });
});

describe("candidateTree (mirrors select_candidate_trees in mozbuild/artifacts.py)", () => {
  const REPO = "https://github.com/vimma-browser/vimma";

  it("is mozilla-release for Vimma's 0.x display versions", () => {
    expect(candidateTree("0.1.0", REPO)).toBe("mozilla-release");
    expect(candidateTree("0.2.0-nightly.20261009", REPO)).toBe("mozilla-release");
  });

  it.each([
    ["0.2.0b1", "mozilla-beta"],
    ["0.2.0a1", "mozilla-central"],
    ["0.2.0esr", "esr"],
  ])("sends display version %s elsewhere (%s)", (display, tree) => {
    expect(candidateTree(display, REPO)).toContain(tree);
  });

  it("sends a source repo containing esr to the ESR trees", () => {
    expect(candidateTree("0.1.0", "https://example.org/vimma-esr")).toContain("esr");
  });
});

describe("indexNamespace", () => {
  it("is the namespace artifacts.py searches for a linux64-opt release build", () => {
    expect(indexNamespace(RELEASE)).toBe(
      `gecko.v2.mozilla-release.shippable.revision.${REV}.firefox.linux64-opt`,
    );
  });

  it("is the mozilla-beta namespace for a beta tarball", () => {
    expect(indexNamespace(BETA)).toBe(
      `gecko.v2.mozilla-beta.shippable.revision.${BETA_REV}.firefox.linux64-opt`,
    );
  });

  it("names the job it is given, such as Apple Silicon's", () => {
    expect(indexNamespace(RELEASE, "macosx64-aarch64-opt")).toBe(
      `gecko.v2.mozilla-release.shippable.revision.${REV}.firefox.macosx64-aarch64-opt`,
    );
  });
});

describe("artifactJob (mirrors the default job in mozbuild/artifacts.py)", () => {
  it("is linux64-opt on x86-64 Linux", () => {
    expect(artifactJob("linux", "x64")).toBe("linux64-opt");
  });

  it("is macosx64-aarch64-opt on Apple Silicon", () => {
    expect(artifactJob("darwin", "arm64")).toBe("macosx64-aarch64-opt");
  });

  it.each([
    ["linux", "arm64"],
    ["darwin", "x64"],
    ["win32", "x64"],
  ])("refuses %s/%s, which no Vimma artifact build supports yet", (platform, arch) => {
    expect(() => artifactJob(platform, arch)).toThrow(
      new RegExp(`no artifact build for ${platform}/${arch}`),
    );
  });
});

describe("machArtifactEnv", () => {
  it("a release tarball passes MOZ_ARTIFACT_REVISION, as mach finds mozilla-release itself", () => {
    expect(machArtifactEnv(RELEASE, "KpoROUtgTjWRzky1Y6nIAg")).toEqual({
      MOZ_ARTIFACT_REVISION: REV,
    });
  });

  it("a beta tarball uses the mozilla-beta index and MOZ_ARTIFACT_TASK, not MOZ_ARTIFACT_REVISION", () => {
    // artifacts.py reads MOZ_ARTIFACT_TASK only when MOZ_ARTIFACT_REVISION is unset, and its
    // revision search never reaches mozilla-beta for Vimma's 0.x display version (spec R6).
    const env = machArtifactEnv(BETA, "ILGA8D1vQYmtIo0RJKNABg");
    expect(env).toEqual({ MOZ_ARTIFACT_TASK: "ILGA8D1vQYmtIo0RJKNABg" });
    expect("MOZ_ARTIFACT_REVISION" in env).toBe(false);
  });
});

describe("indexTask (Taskcluster index findTask response)", () => {
  const NOW = new Date("2026-10-09T12:00:00Z");
  const FOUND = {
    namespace: indexNamespace(RELEASE),
    taskId: "KpoROUtgTjWRzky1Y6nIAg",
    rank: 1791208370,
    data: {},
    expires: "2027-10-05T13:54:14.263Z",
  };
  const NOT_FOUND = { code: "ResourceNotFound", message: "Indexed task not found" };

  it("returns the task and its expiry", () => {
    expect(indexTask(RELEASE, 200, FOUND, NOW)).toEqual({
      taskId: "KpoROUtgTjWRzky1Y6nIAg",
      expires: "2027-10-05T13:54:14.263Z",
    });
  });

  it("names the beta tree when a beta build is missing", () => {
    expect(() => indexTask(BETA, 404, NOT_FOUND, NOW)).toThrow(/mozilla-beta/);
  });

  it("explains a missing build with the revision and a remedy", () => {
    expect(() => indexTask(RELEASE, 404, NOT_FOUND, NOW)).toThrow(
      new RegExp(`${REV}[\\s\\S]*not in the Taskcluster index[\\s\\S]*surfer\\.json`),
    );
  });

  it("explains an expired build with its expiry date", () => {
    const old = { ...FOUND, expires: "2026-10-01T00:00:00.000Z" };
    expect(() => indexTask(RELEASE, 200, old, NOW)).toThrow(/expired 2026-10-01T00:00:00.000Z/);
  });

  it("names the job it looked for, and still says linux64 on Linux", () => {
    const mac = "macosx64-aarch64-opt";
    expect(() => indexTask(RELEASE, 404, NOT_FOUND, NOW, mac)).toThrow(
      /Mozilla's macosx64-aarch64 build of [\s\S]*firefox\.macosx64-aarch64-opt\)/,
    );
    const old = { ...FOUND, expires: "2026-10-01T00:00:00.000Z" };
    expect(() => indexTask(RELEASE, 200, old, NOW, mac)).toThrow(
      /Mozilla's macosx64-aarch64 build of .* expired/,
    );
    expect(() => indexTask(RELEASE, 404, NOT_FOUND, NOW)).toThrow(
      `Mozilla's linux64 build of ${REV} is not in the Taskcluster index ` +
        `(gecko.v2.mozilla-release.shippable.revision.${REV}.firefox.linux64-opt).`,
    );
    expect(() => indexTask(RELEASE, 200, old, NOW)).toThrow(
      `Mozilla's linux64 build of ${REV} expired 2026-10-01T00:00:00.000Z.`,
    );
  });

  it("throws on another HTTP status or a malformed body", () => {
    expect(() => indexTask(RELEASE, 500, {}, NOW)).toThrow(/HTTP 500/);
    expect(() => indexTask(RELEASE, 200, { taskId: 1 }, NOW)).toThrow(/unexpected/);
  });
});

describe("refreshAppIni", () => {
  /** A minimal engine/ with an artifact objdir after `mach build`. */
  const engine = () => {
    const dir = tempDir("vimma-artifact-");
    mkdirSync(join(dir, ARTIFACT_OBJDIR, "dist", "bin", "browser"), { recursive: true });
    mkdirSync(join(dir, "browser"));
    writeFileSync(
      join(dir, "browser", "moz.configure"),
      'imply_option("MOZ_APP_UA_NAME", "Firefox")\n',
    );
    return dir;
  };
  /** @param {string} dir @param {string} buildId */
  const build = (dir, buildId) =>
    writeFileSync(
      join(dir, ARTIFACT_OBJDIR, "dist", "bin", "application.ini"),
      `[App]\nName=Vimma\nBuildID=${buildId}\n`,
    );
  /** @param {string} dir */
  const copy = (dir) =>
    readFileSync(join(dir, ARTIFACT_OBJDIR, "dist", "bin", "browser", "application.ini"), "utf8");

  it("writes the test app file from the current build every time", () => {
    const dir = engine();
    build(dir, "1");
    refreshAppIni(dir);
    expect(copy(dir)).toBe("[App]\nUAName=Firefox\nName=Vimma\nBuildID=1\n");
    build(dir, "2"); // a later bare `./mach build`
    refreshAppIni(dir);
    expect(copy(dir)).toContain("BuildID=2");
  });

  it("returns the path tests pass as XUL_APP_FILE", () => {
    const dir = engine();
    build(dir, "1");
    expect(refreshAppIni(dir)).toBe(
      join(dir, ARTIFACT_OBJDIR, "dist", "bin", "browser", "application.ini"),
    );
  });
});

describe("linkLauncher", () => {
  it("links dist/bin/<binaryName> to firefox before the build, dangling until the unpack", () => {
    // On macOS, browser/app/moz.build copies dist/bin/<MOZ_APP_NAME> into the .app, and make
    // fails when the link is missing; Mozilla's artifact only ships `firefox`.
    const engine = tempDir("vimma-artifact-");
    const launcher = linkLauncher(engine, "vimma");
    expect(launcher).toBe(join(engine, ARTIFACT_OBJDIR, "dist", "bin", "vimma"));
    expect(lstatSync(launcher).isSymbolicLink()).toBe(true);
    expect(readlinkSync(launcher)).toBe("firefox");
  });

  it("leaves an existing launcher or link alone, so it can run again after the build", () => {
    const engine = tempDir("vimma-artifact-");
    linkLauncher(engine, "vimma");
    expect(() => linkLauncher(engine, "vimma")).not.toThrow();
    const bin = join(engine, ARTIFACT_OBJDIR, "dist", "bin");
    writeFileSync(join(bin, "other"), "a real binary");
    linkLauncher(engine, "other");
    expect(lstatSync(join(bin, "other")).isFile()).toBe(true);
  });
});
