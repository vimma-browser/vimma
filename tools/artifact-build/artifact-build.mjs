#!/usr/bin/env node
/**
 * Artifact build of Vimma (ADR-010, spec m0-build-strategy): our front end (JS, CSS, FTL,
 * branding, prefs, patches) built locally on top of Mozilla's compiled binaries for the exact
 * release our source tarball comes from. Used by e2e.yml on GitHub-hosted runners; works locally
 * too, in its own objdir, next to the full build.
 *
 * Run from the repo root after `npm run import`:
 *   node tools/artifact-build/artifact-build.mjs
 * then `npm run mochitest -- --artifact tests/browser/`.
 *
 * It writes engine/mozconfig.artifact from engine/mozconfig and runs `mach build` on Mozilla's
 * build of the revision in engine/sourcestamp.txt (the tarball has no VCS history, so mach cannot
 * guess it): a release tarball passes MOZ_ARTIFACT_REVISION; a Beta tarball (the Beta canary,
 * spec upstream-beta-canary) passes MOZ_ARTIFACT_TASK, the task this tool found in the
 * mozilla-beta index, because mach's revision search never reaches that tree for Vimma's 0.x
 * display version. Then it adapts two things Mozilla's binaries compile in:
 * - the launcher is `firefox`; dist/bin/<binaryName> becomes a symlink to it, as mach expects.
 *   On macOS the link is made before `mach build` too: browser/app/moz.build copies it into the
 *   .app and make stops without it;
 * - the launcher's built-in app data is Mozilla's (Name=Firefox, Vendor=Mozilla). Tests run with
 *   XUL_APP_FILE=dist/bin/browser/application.ini, our application.ini plus `UAName=` from
 *   MOZ_APP_UA_NAME, which a full build compiles into libxul instead.
 */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** Next to, never instead of, the full build's obj-x86_64-pc-linux-gnu. */
export const ARTIFACT_OBJDIR = "obj-artifact";

/**
 * Options of the full build that an artifact build cannot take, with the reason (measured on
 * Firefox 157.0.1, docs/specs/m0-build-strategy.md).
 * @type {Array<[RegExp, string]>}
 */
const DROPPED = [
  [/^ac_add_options\s+--enable-optimize\b/, "configure: not available in this configuration"],
  [/^ac_add_options\s+--enable-hardening\b/, "configure: not available in this configuration"],
  [
    /^ac_add_options\s+--disable-crashreporter\b/,
    "Mozilla's libxul has the crash reporter and aborts without CrashService.sys.mjs",
  ],
  [
    /^ac_add_options\s+--disable-updater\b/,
    "Mozilla's libxul has the updater and aborts without UpdateServiceStub.sys.mjs",
  ],
  [/^ac_add_options\s+--with-ccache\b/, "nothing is compiled"],
];

/**
 * @param {string} mozconfig engine/mozconfig as `npm run import` writes it
 * @returns {string} engine/mozconfig.artifact
 */
export function artifactMozconfig(mozconfig) {
  if (/--enable-artifact-builds\b/.test(mozconfig)) {
    throw new Error("mozconfig already enables artifact builds; pass engine/mozconfig");
  }
  const lines = mozconfig.split("\n").map((line) => {
    const hit = DROPPED.find(([re]) => re.test(line.trim()));
    return hit ? `# artifact build drops: ${line.trim()} (${hit[1]})` : line;
  });
  return [
    "# Generated by tools/artifact-build/artifact-build.mjs from engine/mozconfig (ADR-010).",
    ...lines,
    "",
    "# Artifact build: Mozilla's compiled binaries for this release, our front end on top.",
    "ac_add_options --enable-artifact-builds",
    `mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/${ARTIFACT_OBJDIR}`,
    "",
  ].join("\n");
}

/** The trees whose builds an artifact build can take: the release, and the Beta (canary only). */
export const TREES = ["releases/mozilla-release", "releases/mozilla-beta"];

/**
 * @typedef {{ tree: string, revision: string }} SourceStamp
 */

/**
 * @param {string} sourcestamp engine/sourcestamp.txt of a Firefox source tarball:
 *   the build id, then `https://hg.mozilla.org/<tree>/rev/<40-hex revision>`
 * @returns {SourceStamp} the tree (one of TREES) and the revision
 */
export function sourceStamp(sourcestamp) {
  const match = /^https:\/\/hg\.mozilla\.org\/(\S+)\/rev\/([0-9a-f]{40})\s*$/m.exec(sourcestamp);
  if (!match?.[1] || !match[2]) {
    throw new Error("engine/sourcestamp.txt has no hg.mozilla.org 40-hex revision line");
  }
  const tree = match[1];
  if (!TREES.includes(tree)) {
    throw new Error(
      `engine/sourcestamp.txt names ${tree}; artifact builds take only ${TREES.join(" or ")}`,
    );
  }
  return { tree, revision: match[2] };
}

/**
 * @param {string} mozConfigure engine/browser/moz.configure
 * @returns {string | null} the implied MOZ_APP_UA_NAME, null when upstream's empty default
 */
export function uaName(mozConfigure) {
  return /imply_option\(\s*"MOZ_APP_UA_NAME"\s*,\s*"([^"]+)"\s*\)/.exec(mozConfigure)?.[1] ?? null;
}

/**
 * @param {string} ini dist/bin/application.ini of the artifact build
 * @param {string | null} name MOZ_APP_UA_NAME, see uaName
 * @returns {string} the application.ini tests load through XUL_APP_FILE
 */
export function appIniForArtifact(ini, name) {
  if (name === null) return ini;
  if (!/^\[App\]$/m.test(ini)) throw new Error("application.ini has no [App] section");
  return ini.replace(/^UAName=.*\n/m, "").replace(/^\[App\]$/m, `[App]\nUAName=${name}`);
}

/**
 * The tree mach searches for artifacts, as `select_candidate_trees` in
 * python/mozbuild/mozbuild/artifacts.py decides it: from MOZ_APP_VERSION_DISPLAY (our
 * version_display.txt, not Firefox's version) and MOZ_SOURCE_REPO. It must be mozilla-release
 * so that a release's MOZ_ARTIFACT_REVISION is found; mach has no switch to force the tree, which
 * is why a Beta goes through MOZ_ARTIFACT_TASK instead (machArtifactEnv).
 * @param {string} versionDisplay
 * @param {string} sourceRepo
 * @returns {string}
 */
export function candidateTree(versionDisplay, sourceRepo) {
  if (versionDisplay.includes("esr") || sourceRepo.includes("esr")) return "releases/mozilla-esr*";
  if (/a\d+$/.test(versionDisplay)) return "mozilla-central";
  if (/b\d+$/.test(versionDisplay)) return "releases/mozilla-beta";
  return "mozilla-release";
}

/**
 * The Taskcluster job whose build mach unpacks, as artifacts.py's default job picks it from the
 * target (XP_LINUX or XP_MACOSX, TARGET_CPU) for an `-opt` build. Only the platforms Vimma builds
 * on: x86-64 Linux and Apple Silicon.
 * @param {string} [platform] process.platform
 * @param {string} [arch] process.arch
 * @returns {string}
 */
export function artifactJob(platform = process.platform, arch = process.arch) {
  if (platform === "linux" && arch === "x64") return "linux64-opt";
  if (platform === "darwin" && arch === "arm64") return "macosx64-aarch64-opt";
  throw new Error(
    `no artifact build for ${platform}/${arch}: Vimma's take Mozilla's linux64-opt (linux/x64) ` +
      "or macosx64-aarch64-opt (darwin/arm64) builds",
  );
}

/**
 * The Taskcluster index namespace artifacts.py looks up (`TaskCache.artifacts`: the tree's last
 * path part, `.shippable` for `-opt` jobs, trust domain gecko, product firefox).
 * @param {SourceStamp} stamp
 * @param {string} [job] see artifactJob
 */
export function indexNamespace({ tree, revision }, job = "linux64-opt") {
  // A constant per accepted tree: nothing read from the tarball but the revision reaches the URL.
  const project = tree === "releases/mozilla-beta" ? "mozilla-beta" : "mozilla-release";
  return `gecko.v2.${project}.shippable.revision.${revision}.firefox.${job}`;
}

/**
 * How mach finds Mozilla's build. A release: MOZ_ARTIFACT_REVISION, which mach looks up on
 * mozilla-release itself. A Beta: MOZ_ARTIFACT_TASK, the task found in the mozilla-beta index,
 * because install_from (python/mozbuild/mozbuild/artifacts.py) reads it only when
 * MOZ_ARTIFACT_REVISION is unset and searches mozilla-beta only for a `bN` display version.
 * @param {SourceStamp} stamp
 * @param {string} taskId the indexed task (indexTask)
 * @returns {Record<string, string>} the variables to set; the other one must be unset
 */
export function machArtifactEnv(stamp, taskId) {
  if (stamp.tree === "releases/mozilla-beta") return { MOZ_ARTIFACT_TASK: taskId };
  return { MOZ_ARTIFACT_REVISION: stamp.revision };
}

const INDEX_URL = "https://firefox-ci-tc.services.mozilla.com/api/index/v1/task/";
const REMEDY =
  "Check that surfer.json pins a Firefox release (or, in the Beta canary, a Beta) and that " +
  "`npm run import` ran on its tarball; release and Beta builds are indexed for a year " +
  "(ADR-010). A full build (`npx surfer build`) does not need this.";

/**
 * @param {SourceStamp} stamp
 * @param {number} status HTTP status of the findTask call
 * @param {unknown} body its JSON body
 * @param {Date} now
 * @param {string} [job] see artifactJob
 * @returns {{ taskId: string, expires: string }}
 */
export function indexTask(stamp, status, body, now, job = "linux64-opt") {
  const { revision } = stamp;
  const build = job.replace(/-opt$/, "");
  if (status === 404) {
    throw new Error(
      `Mozilla's ${build} build of ${revision} is not in the Taskcluster index ` +
        `(${indexNamespace(stamp, job)}). ${REMEDY}`,
    );
  }
  if (status !== 200) throw new Error(`Taskcluster index: HTTP ${status} for ${revision}`);
  const task = /** @type {{ taskId?: unknown, expires?: unknown }} */ (body ?? {});
  if (typeof task.taskId !== "string" || typeof task.expires !== "string") {
    throw new Error(`Taskcluster index: unexpected response for ${revision}`);
  }
  if (Date.parse(task.expires) <= now.getTime()) {
    throw new Error(`Mozilla's ${build} build of ${revision} expired ${task.expires}. ${REMEDY}`);
  }
  return { taskId: task.taskId, expires: task.expires };
}

/**
 * Links dist/bin/<binaryName> to `firefox`, Mozilla's launcher, unless something is there already.
 * Before `mach build` the link dangles until the artifact is unpacked; the install manifests only
 * remove files they once installed, so it survives the build.
 * @param {string} engine path of engine/
 * @param {string} binaryName surfer.json's binaryName (MOZ_APP_NAME)
 * @returns {string} the launcher's path
 */
export function linkLauncher(engine, binaryName) {
  const bin = join(engine, ARTIFACT_OBJDIR, "dist", "bin");
  const launcher = join(bin, binaryName);
  mkdirSync(bin, { recursive: true });
  if (!existsSync(launcher) && !isSymlink(launcher)) symlinkSync("firefox", launcher);
  return launcher;
}

/**
 * Writes dist/bin/browser/application.ini (the file tests load via XUL_APP_FILE) from the
 * build's current application.ini, so a later bare `./mach build` never leaves it stale.
 * @param {string} engine path of engine/
 * @returns {string} the written path
 */
export function refreshAppIni(engine) {
  const bin = join(engine, ARTIFACT_OBJDIR, "dist", "bin");
  const out = join(bin, "browser", "application.ini");
  const ini = appIniForArtifact(
    readFileSync(join(bin, "application.ini"), "utf8"),
    uaName(readFileSync(join(engine, "browser", "moz.configure"), "utf8")),
  );
  writeFileSync(out, ini);
  return out;
}

/**
 * @param {string} root repository root
 */
async function main(root) {
  const engine = join(root, "engine");
  const read = (/** @type {string} */ p) => readFileSync(join(engine, p), "utf8");
  if (!existsSync(join(engine, "mozconfig"))) {
    throw new Error("engine/mozconfig is missing; run 'npm run import' first");
  }
  const mozconfig = join(engine, "mozconfig.artifact");
  writeFileSync(mozconfig, artifactMozconfig(read("mozconfig")));
  const stamp = sourceStamp(read("sourcestamp.txt"));
  const display = read("browser/config/vimma/version_display.txt").trimEnd().split("\n").at(-1);
  const repo = /^export MOZ_SOURCE_REPO=(\S*)/m.exec(read("mozconfig"))?.[1] ?? "";
  const tree = candidateTree(display ?? "", repo);
  if (tree !== "mozilla-release") {
    throw new Error(
      `display version ${display} / MOZ_SOURCE_REPO ${repo} make mach look for artifacts on ` +
        `${tree}, but a release's MOZ_ARTIFACT_REVISION is found only on mozilla-release ` +
        `(artifacts.py select_candidate_trees). Use an x.y.z display version for artifact builds.`,
    );
  }
  // sourceStamp already checked both; repeated here, where the file data meets the request.
  const { tree: stampTree, revision } = stamp;
  if (!TREES.includes(stampTree)) throw new Error(`unexpected tree ${stampTree}`);
  if (!/^[0-9a-f]{40}$/.test(revision)) throw new Error("the source revision is not 40 hex");
  // Linux keeps the job it always looked up; only macOS asks artifactJob.
  const job = process.platform === "darwin" ? artifactJob() : "linux64-opt";
  const res0 = await fetch(INDEX_URL + indexNamespace({ tree: stampTree, revision }, job));
  const { taskId, expires } = indexTask(stamp, res0.status, await res0.json(), new Date(), job);
  const artifactEnv = machArtifactEnv(stamp, taskId);
  console.log(
    `artifact-build: Mozilla binaries of ${stamp.tree} ${stamp.revision} (task ${taskId}, ` +
      `indexed until ${expires}), ${Object.keys(artifactEnv)[0]}, objdir engine/${ARTIFACT_OBJDIR}`,
  );

  // browser/app/moz.build copies dist/bin/<binaryName> into the .app; make stops without it.
  if (process.platform === "darwin") {
    linkLauncher(engine, JSON.parse(readFileSync(join(root, "surfer.json"), "utf8")).binaryName);
  }
  const env = { ...process.env, MOZCONFIG: mozconfig, ...artifactEnv };
  if (!("MOZ_ARTIFACT_REVISION" in artifactEnv)) delete env.MOZ_ARTIFACT_REVISION;
  const res = spawnSync("./mach", ["--no-interactive", "build"], {
    cwd: engine,
    stdio: "inherit",
    env,
  });
  if (res.status !== 0) process.exit(res.status ?? 1);

  const bin = join(engine, ARTIFACT_OBJDIR, "dist", "bin");
  const binaryName = JSON.parse(readFileSync(join(root, "surfer.json"), "utf8")).binaryName;
  const launcher = join(bin, binaryName);
  if (!existsSync(launcher) && !isSymlink(launcher)) symlinkSync("firefox", launcher);
  refreshAppIni(engine);
  console.log(`artifact-build: done; run 'npm run mochitest -- --artifact tests/browser/'`);
}

/** @param {string} path */
function isSymlink(path) {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(fileURLToPath(new URL("../../", import.meta.url))).catch((e) => {
    console.error(`artifact-build: ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
