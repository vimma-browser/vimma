#!/usr/bin/env node
// Rebuilds packages/vimma-core/src/vendor/smol-toml/smol-toml.mjs from an unpacked smol-toml
// npm tarball (spec m5-core-config-and-theme § Settled). Usage:
//   npm pack smol-toml@<version> && tar xzf smol-toml-<version>.tgz
//   node tools/vendor-smol-toml.mjs package
// The parse-path modules of dist/ are joined into one ES module, in dependency order, with their
// relative imports removed and the upstream licence header kept once at the top. One file because
// `surfer license-check` accepts a non-MPL file in src/ only via a marker comment, and its marker
// regex is global, so it only works reliably for a single such file per run.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MODULES = ["error", "date", "util", "primitive", "struct", "extract", "parse"];
const pkg = process.argv[2];
if (!pkg) {
  console.error("usage: node tools/vendor-smol-toml.mjs <unpacked package dir>");
  process.exit(2);
}
const { name, version } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
if (name !== "smol-toml") throw new Error(`expected smol-toml, got ${name}`);

const out = new URL("../packages/vimma-core/src/vendor/smol-toml/", import.meta.url);
const HEADER = /^\/\*![\s\S]*?\*\/\n/;
let header = "";
const parts = MODULES.map((m) => {
  const src = readFileSync(join(pkg, "dist", `${m}.js`), "utf8");
  const h = HEADER.exec(src)?.[0];
  if (!h) throw new Error(`${m}.js: no licence header`);
  if (header && h !== header) throw new Error(`${m}.js: licence header differs`);
  header = h;
  const body = src
    .slice(h.length)
    .replace(/^import \{[^}]*\} from '\.\/[a-z]+\.js';\n/gm, "")
    .trimEnd();
  if (/from '\.\//.test(body)) throw new Error(`${m}.js: unexpected relative import left`);
  return `// ---- smol-toml ${version} dist/${m}.js ----\n${body}\n`;
});

writeFileSync(
  new URL("smol-toml.mjs", out),
  `${header}// Vendored for vimma: smol-toml ${version}, generated by tools/vendor-smol-toml.mjs; ` +
    "do not edit.\n" +
    "// Modified for vimma: the dist/ modules joined into one file, their relative imports " +
    "removed;\n// code otherwise unchanged. The notice ships in about:license " +
    `(licence/body.html).\n\n${parts.join("\n")}\n` +
    "// Ignore license in this file: BSD-3-Clause (header above); see README.md.\n",
);
copyFileSync(join(pkg, "LICENSE"), new URL("LICENSE", out));
console.log(`vendored smol-toml ${version} -> ${out.pathname}smol-toml.mjs`);
