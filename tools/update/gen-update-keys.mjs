/**
 * npm run gen-update-keys: writes packages/vimma-core/src/updates/update-keys.mjs, the keys the
 * manifest check pins, from the certificates Firefox's updater embeds
 * (configs/updater/primary.der and secondary.der, which npm run import links to where
 * toolkit/mozapps/update/updater/moz-build.patch reads them). One source for both verifiers
 * (docs/specs/m6a-updater.md "Delivery", sub-PR 2): a key can only be trusted by the manifest
 * check if the updater trusts it too, and the other way round.
 *
 *   gen-update-keys.mjs [--certs DIR] [--out FILE] [--check]
 *       --check fails, writing nothing, when FILE differs from what the certificates give
 *
 * A secondary certificate that holds the primary's key again (decision 39, until the offline
 * ceremony) gives one pinned key, not two.
 */

import { X509Certificate, createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { CERT_DIR } from "./cert-dir.mjs";

export { CERT_DIR };
export const UPDATE_KEYS_FILE = "packages/vimma-core/src/updates/update-keys.mjs";

/** @typedef {{ slot: "primary" | "secondary", spki: Uint8Array }} SlotKey */

/**
 * @param {string} dir a directory with primary.der and secondary.der
 * @returns {[SlotKey, SlotKey]} the primary, then the secondary
 */
export function readCertificates(dir) {
  /** @param {SlotKey["slot"]} slot @returns {SlotKey} */
  const read = (slot) => {
    const file = join(dir, `${slot}.der`);
    let cert;
    try {
      cert = new X509Certificate(readFileSync(file));
    } catch (e) {
      throw new Error(`${file}: not a DER certificate (${e instanceof Error ? e.message : e})`, {
        cause: e,
      });
    }
    const key = cert.publicKey;
    // The updater reads only the key, but a certificate the key did not sign is not the one the
    // ceremony made (docs/runbook.md step 5b).
    if (!cert.verify(key)) {
      throw new Error(`${file}: not self-signed by its own key`);
    }
    if (key.asymmetricKeyType !== "rsa" || key.asymmetricKeyDetails?.modulusLength !== 4096) {
      throw new Error(`${file}: update keys are RSA-4096 (docs/specs/m6a-updater.md §6)`);
    }
    return { slot, spki: new Uint8Array(key.export({ type: "spki", format: "der" })) };
  };
  return [read("primary"), read("secondary")];
}

const HEADER = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// Generated by \`npm run gen-update-keys\` (tools/update/gen-update-keys.mjs) from the
// certificates Firefox's updater embeds,
// ${CERT_DIR}/*.der. Edit those, then run it again.

/**
 * The public update keys this build trusts for the update manifest (docs/specs/m6a-updater.md
 * §6), each as base64 DER SubjectPublicKeyInfo with its id, the first 8 hex digits of the SPKI's
 * SHA-256. Signatures are RSASSA-PKCS1-v1_5 with SHA-384. updates.test.mjs checks each entry
 * (RSA-4096, the id matches, one key per slot) and the primary's SHA-256 against the one
 * recorded in docs/runbook.md ("Update signing keys").
 *
 * The primary is the Google Cloud KMS key update-primary (key ring vimma-updates, version 1,
 * RSA_SIGN_RAW_PKCS1_4096 in an HSM). Until the offline key ceremony makes the secondary
 * (recovery) key, the updater's secondary slot holds the primary's certificate again (decision
 * 39), and only the primary is pinned here. Pinning the secondary is an ordinary release
 * announced by a manifest the primary signs. Until then, a lost or leaked primary cannot be
 * replaced through the update check: installs keep trusting it until they are updated by hand.
 * @type {readonly import("./updates.mjs").PinnedKey[]}
 */
`;

/**
 * The text of update-keys.mjs for these keys, formatted as prettier formats it.
 * @param {[SlotKey, SlotKey]} keys from readCertificates
 * @returns {Promise<string>}
 */
export async function renderUpdateKeys(keys) {
  const [primary, secondary] = keys;
  const pinned = Buffer.from(secondary.spki).equals(Buffer.from(primary.spki))
    ? [primary]
    : [primary, secondary];
  const entries = pinned.map(({ slot, spki }) => {
    const id = createHash("sha256").update(spki).digest("hex").slice(0, 8);
    const b64 = Buffer.from(spki).toString("base64");
    const chunks = b64.match(/.{1,88}/g) ?? [];
    return (
      `  Object.freeze({\n    id: ${JSON.stringify(id)},\n    slot: ${JSON.stringify(slot)},\n` +
      `    spki:\n      ${chunks.map((c) => JSON.stringify(c)).join(" +\n      ")},\n  }),\n`
    );
  });
  const text = `${HEADER}export const UPDATE_KEYS = Object.freeze([\n${entries.join("")}]);\n`;
  const prettier = await import("prettier");
  const root = fileURLToPath(new URL("../../", import.meta.url));
  const options = await prettier.resolveConfig(join(root, UPDATE_KEYS_FILE));
  return prettier.format(text, { ...options, filepath: join(root, UPDATE_KEYS_FILE) });
}

/** @param {string[]} argv */
async function main(argv) {
  const root = fileURLToPath(new URL("../../", import.meta.url));
  let certs = join(root, CERT_DIR);
  let out = join(root, UPDATE_KEYS_FILE);
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    const value = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${flag} needs a value`);
      return v;
    };
    if (flag === "--certs") certs = value();
    else if (flag === "--out") out = value();
    else if (argv[i] === "--check") check = true;
    else throw new Error(`unexpected argument: ${argv[i]}`);
  }
  const text = await renderUpdateKeys(readCertificates(certs));
  if (check) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {
      // A missing file differs.
    }
    if (current !== text) {
      throw new Error(
        `${out} differs from the certificates in ${certs}; run npm run gen-update-keys`,
      );
    }
    console.log(`${out}: up to date`);
    return;
  }
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((e) => {
    console.error(`gen-update-keys: ${e instanceof Error ? e.message : e}`);
    process.exit(1);
  });
}
